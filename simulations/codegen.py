"""Generate the fixed-size, matrix-update OSQP solver used by airbrakes.

Run with the simulations virtual environment; no RocketPy/network data is used.
Only files listed in the generated library's manifest are owned by this script.
"""
import argparse
import hashlib
import importlib.metadata
import json
from pathlib import Path
import re
import tempfile

import numpy as np
import osqp
from scipy import sparse

from linearmodel import MPCConfig

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "airbrakes/lib/osqp_mpc"
OSQP_VERSION = "1.1.3"


def make_solver(config=None):
    """Use the Python reference's initial sparsity, scaling, and tolerances.

    Fix rho adaptation to an iteration interval so it does not depend on host
    timing. All upper-triangle entries are stored, even when later set to zero.
    """
    config = config or MPCConfig()
    n = config.horizon
    difference = np.eye(n) - np.eye(n, k=-1)
    rows, cols = np.triu_indices(n)
    p = sparse.csc_matrix((np.ones(len(rows)), (rows, cols)), shape=(n, n))
    a = sparse.vstack((sparse.eye(n), sparse.csc_matrix(difference)), format="csc")
    rates = np.full(n, config.max_deployment_rate * config.prediction_dt)
    rates[0] = config.max_deployment_rate / 10.0
    solver = osqp.OSQP()
    solver.setup(P=p, q=np.zeros(n), A=a,
                 l=np.r_[np.zeros(n), -rates],
                 u=np.r_[np.ones(n), rates], verbose=False,
                 warm_starting=True, max_iter=1500,
                 eps_abs=1e-5, eps_rel=1e-5, adaptive_rho_interval=50)
    return solver, p, a


def stable_text(path):
    # OSQP writes the wall-clock generation timestamp into four comment blocks.
    return re.sub(r"autogenerated by OSQP on [^\r\n]*",
                  "autogenerated by OSQP (see generation.json)",
                  path.read_text(encoding="utf-8"))


def generate():
    if osqp.__version__ != OSQP_VERSION:
        raise RuntimeError(f"Expected OSQP {OSQP_VERSION}, found {osqp.__version__}; "
                           "use simulations/.venv or uv sync --locked")
    config = MPCConfig()
    solver, p, a = make_solver(config)
    files = {}
    with tempfile.TemporaryDirectory(prefix="airbrake-osqp-") as temporary:
        output = Path(temporary) / "generated"
        solver.codegen(str(output), parameters="matrices", prefix="airbrake_",
                       extension_name=None, use_float=False,
                       printing_enable=False, profiling_enable=False,
                       interrupt_enable=False, compile=False)
        sources = (list((output / "src").glob("*.c"))
                   + list((output / "inc/public").glob("*.h"))
                   + list((output / "inc/private").glob("*.h"))
                   + [output / "osqp_configure.h", output / "airbrake_workspace.h",
                      output / "airbrake_workspace.c"])
        for source in sources:
            files[f"src/osqp_mpc/{source.name}"] = stable_text(source)
    # The version.h template supplied by OSQP otherwise reports 1.0.0.
    files["src/osqp_mpc/version.h"] = (
        f'#ifndef OSQP_VERSION\n#define OSQP_VERSION "{OSQP_VERSION}"\n#endif\n')
    files["src/osqp_mpc/mpc_dimensions.h"] = (
        "/* Generated by simulations/codegen.py. Regenerate to change horizon. */\n"
        "#ifndef MPC_DIMENSIONS_H\n#define MPC_DIMENSIONS_H\n"
        f"#define MPC_HORIZON {config.horizon}\n"
        f"#define MPC_CONSTRAINTS {a.shape[0]}\n"
        f"#define MPC_P_NNZ {p.nnz}\n"
        "#define MPC_SOLVER_MAX_ITER 1500\n"
        "#define MPC_SOLVER_EPS 1e-5\n"
        "#define MPC_SOLVER_RHO_INTERVAL 50\n"
        "#endif\n")
    # Local source-relative includes avoid the older example headers in include/.
    files["library.json"] = json.dumps({
        "name": "OSQP MPC", "version": OSQP_VERSION,
        "description": "Generated allocation-free airbrake QP solver",
        "license": "Apache-2.0", "build": {"srcDir": "src"},
    }, indent=2) + "\n"
    distribution = importlib.metadata.distribution("osqp")
    license_file = next(f for f in distribution.files
                        if str(f).endswith("licenses/LICENSE"))
    files["LICENSE"] = distribution.locate_file(license_file).read_text(encoding="utf-8")
    manifest = {
        "generator": "simulations/codegen.py", "osqp_version": OSQP_VERSION,
        "numpy_version": np.__version__, "horizon": config.horizon,
        "constraints": a.shape[0], "p_nnz": p.nnz, "a_nnz": a.nnz,
        "parameters": "matrices", "precision": "double",
        "max_iter": 1500, "eps_abs": 1e-5, "eps_rel": 1e-5,
        "adaptive_rho_interval": 50,
        "files": {name: hashlib.sha256(content.encode()).hexdigest()
                  for name, content in sorted(files.items())},
    }
    files["generation.json"] = json.dumps(manifest, indent=2) + "\n"
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Regenerate in temporary storage and verify checked-in output")
    args = parser.parse_args()
    files = generate()
    if args.check:
        mismatches = [name for name, text in files.items()
                      if not (DESTINATION / name).is_file()
                      or (DESTINATION / name).read_text(encoding="utf-8") != text]
        if mismatches:
            raise SystemExit("Generated files differ: " + ", ".join(mismatches))
        print(f"Verified {len(files)} generated files")
        return
    for name, text in files.items():
        target = DESTINATION / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    print(f"Generated {len(files)} files in {DESTINATION}")


if __name__ == "__main__":
    main()
